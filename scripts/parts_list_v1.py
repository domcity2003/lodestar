"""Lodestar v1 (revision v1.1) parts list: purchased parts with price and source, airframe materials, and the
mass line list with maturity.

Sources:
  prices   cost_model.COMMON with the v1.1 changes in cost_v1_1.py (REMOVE / ADD), SiCore cells at
           cost_trades.SICORE_PRICE (no public price; mid estimate), foam-core airframe materials from cost_model.BUILD
  masses   out/mass_growth/lines.csv (SiCore build, kit on), maturity per AIAA S-120A-style classes

Run:    ../.venv/Scripts/python.exe -X utf8 parts_list_v1.py      (from scripts/)
Writes: out/parts_list/parts_cost.csv, out/parts_list/mass_lines.csv, docs/parts_list.md
"""
from pathlib import Path

import pandas as pd

import cost_model as cm
import cost_v1_1 as c11
from cost_trades import SICORE_PRICE
import lodestar_v1 as v1

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "out" / "parts_list"
DOC = ROOT / "docs" / "parts_list.md"

SICORE = cm.Item("power", "Cells: Amprius SiCore 6.3 Ah 18650 (30, 6S5P in the wing roots)", 30, SICORE_PRICE["mid"],
                 SICORE_PRICE["low"], SICORE_PRICE["high"],
                 "ESTIMATE: no public unit price; $10-35 range (research/2026-11-12-cost-model.md)")


def parts():
    items = [i for i in cm.COMMON if not i.name.startswith(tuple(c11.REMOVE)) and not i.name.startswith("Cells:")]
    items += [SICORE] + c11.ADD
    b = cm.BUILD["foam-core"]
    items.append(cm.Item("airframe", "Airframe materials: EPS 20 / XPS cores, glass and carbon, Rohacell web, G10, epoxy",
                         1, b["materials"], b["mat_lo"], b["mat_hi"], "ESTIMATE (cost_model.BUILD foam-core)"))
    order = ["airframe", "propulsion", "power", "avionics", "payload", "safety", "kit system"]
    df = pd.DataFrame([dict(group=i.group, item=i.name, qty=i.qty, unit_usd=i.unit, line_usd=i.qty * i.unit,
                            low_usd=i.qty * i.low, high_usd=i.qty * i.high, source=i.source) for i in items])
    df["group"] = pd.Categorical(df.group, order, ordered=True)
    return df.sort_values(["group", "line_usd"], ascending=[True, False]).reset_index(drop=True)


def ground():
    return pd.DataFrame([dict(item=i.name, qty=i.qty, unit_usd=i.unit, low_usd=i.low, high_usd=i.high, source=i.source)
                         for i in cm.GROUND])


def md_table(df, cols, fmt):
    head = "| " + " | ".join(cols.values()) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    rows = []
    for r in df.itertuples(index=False):
        rows.append("| " + " | ".join(fmt.get(c, str)(getattr(r, c)) for c in cols) + " |")
    return head + "\n".join(rows)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    DOC.parent.mkdir(parents=True, exist_ok=True)
    p = parts()
    p.to_csv(OUT / "parts_cost.csv", index=False)
    m = pd.read_csv(ROOT / "out" / "mass_growth" / "lines.csv")
    m.to_csv(OUT / "mass_lines.csv", index=False)
    g = ground()

    usd = lambda x: f"${x:,.0f}"
    qty = lambda x: f"{x:g}"
    by_group = p.groupby("group", observed=True)[["line_usd", "low_usd", "high_usd"]].sum().reset_index()
    total = p[["line_usd", "low_usd", "high_usd"]].sum()
    mass_total = m.basic_kg.sum()
    pred_total = m.predicted_kg.sum()
    by_cat = m.groupby("category")[["basic_kg", "predicted_kg"]].sum().sort_values("basic_kg", ascending=False).reset_index()

    text = f"""# Lodestar v1 parts list

Design revision {v1.VERSION}, {v1.FROZEN}. One aircraft, SiCore battery build, foam-core wing, rescue kit fitted.
Generated by `scripts/parts_list_v1.py` from the cost model (`scripts/cost_model.py`, `scripts/cost_v1_1.py`) and the
mass growth line list (`scripts/mass_growth.py`). Prices were found 2026-11-12 to 2026-11-16; lines marked ESTIMATE have no
quoted price. Unit cost for a 10-aircraft build including labour and tooling is in `out/cost_v1.1/unit_cost.csv`.

## Purchased parts and materials

Parts and materials total **{usd(total.line_usd)}** (range {usd(total.low_usd)} to {usd(total.high_usd)}).

{md_table(by_group, dict(group="Group", line_usd="Total", low_usd="Low", high_usd="High"), dict(line_usd=usd, low_usd=usd, high_usd=usd))}

Table 1. Parts and materials cost by group [USD, one aircraft].

{md_table(p, dict(group="Group", item="Item", qty="Qty", unit_usd="Unit", line_usd="Line", source="Source"), dict(qty=qty, unit_usd=usd, line_usd=usd))}

Table 2. Purchased parts and materials, one aircraft [USD]. Unit = mid price; ranges in `out/parts_list/parts_cost.csv`.

## Ground equipment (per team, not per aircraft)

{md_table(g, dict(item="Item", qty="Qty", unit_usd="Unit", source="Source"), dict(qty=qty, unit_usd=usd))}

Table 3. Ground equipment shared by a team [USD].

## Mass lines

Basic mass **{mass_total:.3f} kg**; predicted mass with the growth allowance **{pred_total:.3f} kg** against the 10 kg limit
(SiCore, kit on). Maturity: Measured (datasheet or weighed), Calculated (from geometry and density), Estimated (budget).
Growth allowance per class from `scripts/mass_growth.py` (AIAA S-120A-style).

{md_table(by_cat, dict(category="Category", basic_kg="Basic [kg]", predicted_kg="Predicted [kg]"), dict(basic_kg=lambda x: f"{x:.3f}", predicted_kg=lambda x: f"{x:.3f}"))}

Table 4. Mass by category, basic and with growth allowance [kg].

{md_table(m, dict(item="Item", basic_kg="Basic [kg]", x_m="x [m]", maturity="Maturity", mga_pct="Allowance [%]", basis="Basis"), dict(basic_kg=lambda x: f"{x:.3f}", x_m=lambda x: f"{x:.3f}", mga_pct=lambda x: f"{x:g}"))}

Table 5. Mass line list, SiCore build with kit [kg; x from the root leading edge, aft positive].
"""
    DOC.write_text(text, encoding="utf-8")
    print(f"parts {total.line_usd:,.0f} USD ({len(p)} lines); basic mass {mass_total:.3f} kg, predicted {pred_total:.3f} kg")
    print(f"wrote {DOC.relative_to(ROOT)} and {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
